// Extract everything the models cannot own, from a reference database.
//
// Model-first splits the schema in two:
//
//   src/db/schema/   the models own tables, columns, indexes, foreign keys,
//                    views and enums. `db:generate` writes migrations for them.
//   db/functions/    functions, triggers, scheduled jobs, grants and seed rows
//                    and seed rows. Re-applied in full after every migration —
//                    every statement is CREATE OR REPLACE or an idempotent
//                    upsert — so they can never drift from a column that just
//                    moved underneath them.
//
// POLICIES ARE GONE. They were the reason this script had to exist at all —
// drizzle-kit can express pgPolicy but cannot round-trip one, and introspection
// dropped the USING expression from 32 of 47, which turns each into "permit
// everyone". Authorization is in the API now; see db/functions/015_no_rls.sql.
//
// Read from the live catalog rather than from the migration history: the 72
// legacy files redefine the same function up to five times, and only the
// database knows which definition survived.
//
//   DATABASE_URL=… node scripts/extract-programmables.mjs
import { mkdirSync, writeFileSync, rmSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import pg from 'pg';
import 'dotenv/config';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'db', 'functions');
const NL = '\n';

if (!process.env.DATABASE_URL) {
  console.error('[extract] DATABASE_URL is not set');
  process.exit(1);
}

const client = new pg.Client({
  connectionString: process.env.DATABASE_URL,
  ssl: process.env.DATABASE_SSL === '1' ? { rejectUnauthorized: false } : undefined,
});
await client.connect();

// `storage` is gone — Supabase Storage's schema, replaced by
// public.attachments. `auth` still holds uid(), which server_now() and
// roster_maker_data() call.
const SCHEMAS = `('public', 'auth')`;
const ROLES = `('anon', 'authenticated', 'service_role', 'supabase_auth_admin')`;

const header = (what) =>
  [
    '-- GENERATED by scripts/extract-programmables.mjs from a reference database.',
    `-- ${what}`,
    '-- Re-applied after every migration; every statement is idempotent.',
    '',
    '',
  ].join(NL);

const literal = (v) => `'${String(v).replace(/'/g, "''")}'`;
const quoteIdent = (v) => `"${String(v).replace(/"/g, '""')}"`;

/* ----------------------------------------------------------------- functions */

// Extension-owned functions (postgis, pgcrypto, pg_cron, vector) belong to the
// extension, not to this schema.
const { rows: functions } = await client.query(`
  select n.nspname as schema, p.proname as name,
         pg_get_function_identity_arguments(p.oid) as args,
         pg_get_functiondef(p.oid) as def
    from pg_proc p
    join pg_namespace n on n.oid = p.pronamespace
   where n.nspname in ${SCHEMAS}
     and p.oid not in (
       select objid from pg_depend where deptype = 'e' and classid = 'pg_proc'::regclass
     )
   order by n.nspname, p.proname, args
`);

// Privileges travel with the function: several are revoked from public and
// granted only to service_role, and losing that turns an internal helper into
// something any signed-in member can call.
const { rows: fnGrants } = await client.query(`
  select n.nspname as schema, p.proname as name,
         pg_get_function_identity_arguments(p.oid) as args,
         pg_get_userbyid(a.grantee) as grantee,
         a.privilege_type
    from pg_proc p
    join pg_namespace n on n.oid = p.pronamespace
    cross join lateral aclexplode(coalesce(p.proacl, acldefault('f', p.proowner))) a
   where n.nspname in ${SCHEMAS}
     and p.oid not in (
       select objid from pg_depend where deptype = 'e' and classid = 'pg_proc'::regclass
     )
     and pg_get_userbyid(a.grantee) in ${ROLES}
   order by 1, 2, 3, 4
`);

const grantsByFn = new Map();
for (const g of fnGrants) {
  const key = `${g.schema}.${g.name}(${g.args})`;
  if (!grantsByFn.has(key)) grantsByFn.set(key, new Set());
  grantsByFn
    .get(key)
    .add(`grant ${g.privilege_type.toLowerCase()} on function ${key} to ${g.grantee};`);
}

// 012_app_functions.sql is AUTHORED and must not be swept back in here: a
// re-extract would duplicate it, and the next one after a schema change
// would capture a stale copy. Skip anything this project added.
const AUTHORED = new Set(['slot_concluded', 'time_minutes']);

// Retired by the move to a Node API — see db/functions/005_drop_retired.sql.
// Excluded here as well, or a re-extract from a database that predates the
// drop would quietly bring them back.
const RETIRED = new Set([
  'custom_access_token_hook',
  'public_branding',
  'my_member_code',
  'clear_image_paths',
  // Passwords: all six moved to src/services/authService.ts.
  'verify_member_login',
  'change_member_password',
  'set_member_password',
  'verify_master_password',
  'set_master_password',
  'master_password_is_set',
  // Acting on yourself: moved to src/services/profileService.ts.
  'mark_enrolled',
  'mark_password_changed',
  'update_my_profile',
  // The RLS helpers. They existed only to be called from policy expressions,
  // and there are no policies — see 015_no_rls.sql, which drops them.
  'admin_can_access',
  'is_admin',
  'is_superadmin',
  'admin_branch_ids',
  'admin_group_ids',
  'admin_has_assignments',
  'current_app_role',
  'my_member_id',
  'attachment_folder',
]);

let fnSql = header('Functions, with their privileges. Authored ones live in 012.');
for (const f of functions) {
  if (AUTHORED.has(f.name) || RETIRED.has(f.name)) continue;
  const key = `${f.schema}.${f.name}(${f.args})`;
  fnSql += f.def.trimEnd() + ';' + NL;
  const g = grantsByFn.get(key);
  if (g) {
    // Revoke first: re-applying must not leave behind a privilege an earlier
    // version granted and this one does not.
    fnSql += `revoke all on function ${key} from public, anon, authenticated, service_role;` + NL;
    fnSql += [...g].join(NL) + NL;
  }
  fnSql += NL;
}

/* ------------------------------------------------------------------ policies */

// NOT EXTRACTED ANY MORE. Row-level security is off; authorization lives in
// src/domain/access and src/services/accessService.ts, with unit tests.
//
// This block used to read 47 policies out of pg_policies and write them to
// 015_policies.sql. db/functions/015_no_rls.sql now drops every policy and
// disables RLS instead, so a database restored from an older dump converges on
// the current model rather than resurrecting the old one.
//
// Left as a comment rather than deleted, because the reason matters: it is the
// last thing this generator did that the API could not.

/* ------------------------------------------------------------------ triggers */

const { rows: triggers } = await client.query(`
  select c.relname as table, t.tgname as name, pg_get_triggerdef(t.oid) as def
    from pg_trigger t
    join pg_class c on c.oid = t.tgrelid
    join pg_namespace n on n.oid = c.relnamespace
   where n.nspname = 'public' and not t.tgisinternal
   order by c.relname, t.tgname
`);

let trgSql = header('Triggers. Dropped and recreated so the definition is exact.');
for (const t of triggers) {
  trgSql += `drop trigger if exists ${t.name} on public.${t.table};` + NL;
  trgSql += t.def + ';' + NL + NL;
}

/* ----------------------------------------------------------------- cron jobs */

// Scheduled in db/functions/032_cron_app.sql, for the same reason 012 and 014
// exist: reading it back out of cron.job would put it in both files.
const AUTHORED_JOBS = new Set(['cleanup-expired-refresh-tokens']);

let cronSql = header('Scheduled jobs (pg_cron).');
let jobCount = 0;
try {
  const { rows: jobs } = await client.query(
    `select jobname, schedule, command from cron.job order by jobname`,
  );
  jobCount = jobs.length;
  for (const j of jobs) {
    if (AUTHORED_JOBS.has(j.jobname)) continue;
    cronSql += [
      'do $cron$',
      'begin',
      `  if exists (select 1 from cron.job where jobname = ${literal(j.jobname)}) then`,
      `    perform cron.unschedule(${literal(j.jobname)});`,
      '  end if;',
      'end',
      '$cron$;',
      `select cron.schedule(${literal(j.jobname)}, ${literal(j.schedule)}, ${literal(j.command)});`,
      '',
      '',
    ].join(NL);
  }
} catch {
  cronSql += '-- pg_cron is not installed in this database.' + NL;
}

/* ---------------------------------------------------------------- privileges */

// TABLE privileges are NOT extracted. db/functions/040_grants.sql is authored
// by hand, because what privileges should exist is a decision and the database
// we migrated from is the wrong place to read it from: Supabase granted them at
// project provisioning, so they appear in no migration and a rebuilt database
// has none of them. Extracting from such a database would faithfully reproduce
// "permission denied for table branches" on every request.
//
// FUNCTION privileges above ARE extracted: those were written in the migrations
// deliberately (several helpers are revoked from public and granted only to
// service_role), so the database is the right record of them.

/* ---------------------------------------------------------------------- seed */

// Rows the schema cannot work without. Column DEFAULTS fill app_settings, so a
// fresh deployment does not inherit whatever this database happens to hold.
//
// The three storage.buckets rows used to be seeded here. There is no buckets
// table now: the buckets and which of them is public are constants in
// src/storage/objects.ts, so there is nothing left to seed but app_settings.
let seedSql = header('Rows the schema cannot work without.');
seedSql += 'insert into public.app_settings (id) values (1) on conflict (id) do nothing;' + NL;

/* --------------------------------------------------------------------- write */

// Only the files this script OWNS are replaced. It used to wipe the whole
// directory, which silently deleted the authored ones beside them — the drops,
// the app's own functions and the grants — and the next deployment came up with
// no privileges at all. A generator must never remove what it did not write.
const GENERATED = [
  '010_functions.sql',
  '020_triggers.sql',
  '030_cron.sql',
  '050_seed.sql',
];
mkdirSync(OUT, { recursive: true });
for (const name of GENERATED) rmSync(join(OUT, name), { force: true });

writeFileSync(join(OUT, '010_functions.sql'), fnSql, 'utf8');
writeFileSync(join(OUT, '020_triggers.sql'), trgSql, 'utf8');
writeFileSync(join(OUT, '030_cron.sql'), cronSql, 'utf8');
writeFileSync(join(OUT, '050_seed.sql'), seedSql, 'utf8');

console.log(
  `[extract] ${functions.length} function(s), ` +
    `${triggers.length} trigger(s), ${jobCount} job(s), ` +
    `-> db/functions/  (040_grants.sql and 015_no_rls.sql are authored)`,
);

await client.end();
